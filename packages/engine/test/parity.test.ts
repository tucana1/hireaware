import { describe, expect, it } from 'vitest';
import model from '../model/risk-model.json';
import fixtures from './fixtures/parity.json';
import { RiskClassifier, type RiskModelJson } from '../src/classifier';

const classifier = new RiskClassifier(model as unknown as RiskModelJson);

describe('classifier parity with Python', () => {
  it('has fixtures generated by model-recruitment-risk.py', () => {
    expect(fixtures.cases.length).toBeGreaterThan(100);
    expect(fixtures.classes).toEqual(classifier.classes);
  });

  // The TS classifier must match the pure-Python JSON inference almost exactly, and scikit-learn itself
  // to within the rounding applied to the exported weights.
  it.each(fixtures.cases.map((c, i) => [i, c] as const))('case %i', (_i, c) => {
    const result = classifier.predict(c.text);
    if (c.json_proba === null) {
      expect(result).toBeNull();
      return;
    }
    expect(result).not.toBeNull();
    const probs = classifier.classes.map((k) => result!.probs[k]);
    probs.forEach((p, k) => {
      expect(Math.abs(p - c.json_proba![k]!)).toBeLessThan(1e-9);
      expect(Math.abs(p - c.sklearn_proba![k]!)).toBeLessThan(2e-3);
    });
  });
});
